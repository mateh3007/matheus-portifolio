import { chromium } from '@playwright/test'
const out = process.env.OUT
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 800 }, reducedMotion: 'reduce' })
const p = await ctx.newPage()
await p.goto('http://localhost:4173/'); await p.waitForTimeout(500)
await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(200)
await p.screenshot({ path: `${out}/s-menu.png` })
await p.keyboard.press('Escape')
await p.evaluate(() => document.getElementById('projects').scrollIntoView())
await p.getByRole('button', { name: /View case study/ }).first().click(); await p.waitForTimeout(300)
await p.screenshot({ path: `${out}/s-dialog-m.png` })
await ctx.close()
const c2 = await b.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' })
const q = await c2.newPage()
await q.goto('http://localhost:4173/'); await q.waitForTimeout(500)
await q.evaluate(() => document.getElementById('projects').scrollIntoView())
await q.getByRole('button', { name: /View case study/ }).nth(2).click(); await q.waitForTimeout(300)
await q.screenshot({ path: `${out}/s-dialog-d.png` })
await b.close()
